import 'dart:convert';
import 'dart:io';

/// Run from the project root after editing lib/l10n/{en,ko,ja}.json.
void main() {
  final catalogs = <String, Map<String, dynamic>>{};
  for (final code in ['en', 'ko', 'ja']) {
    catalogs[code] =
        jsonDecode(File('lib/l10n/$code.json').readAsStringSync())
            as Map<String, dynamic>;
  }
  final english = catalogs['en']!;
  Set<String> placeholders(String text) =>
      RegExp(r'\{\d+\}').allMatches(text).map((m) => m[0]!).toSet();
  for (final entry in catalogs.entries) {
    if (entry.value.keys.toSet().difference(english.keys.toSet()).isNotEmpty ||
        english.keys.toSet().difference(entry.value.keys.toSet()).isNotEmpty) {
      throw StateError('Translation keys differ: ${entry.key}');
    }
    for (final key in english.keys) {
      final value = entry.value[key];
      if (value is! String ||
          value.trim().isEmpty ||
          !placeholders(
            value,
          ).containsAll(placeholders(english[key] as String)) ||
          !placeholders(
            english[key] as String,
          ).containsAll(placeholders(value))) {
        throw StateError(
          'Invalid translation or placeholders: ${entry.key}/$key',
        );
      }
    }
  }
  final encoded = const JsonEncoder.withIndent(
    '  ',
  ).convert(catalogs).replaceAll(r'$', r'\$');
  File('lib/l10n/catalogs.dart').writeAsStringSync(
    '// Generated by dart run tool/generate_localizations.dart. Do not edit.\nconst translations = $encoded;\n',
  );
}
